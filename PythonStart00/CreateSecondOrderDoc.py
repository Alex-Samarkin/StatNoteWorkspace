def write_file(target: Path, content: str, make_backup: bool, stamp: str) -> tuple[bool, int]:
    """Записывает файл с резервной копией и проверкой целостности."""
    target.parent.mkdir(parents=True, exist_ok=True)

    if target.exists() and make_backup:
        backup = target.with_name(f"{target.name}.{stamp}.bak")
        shutil.copy2(target, backup)

    payload = content.encode("utf-8")
    target.write_bytes(payload)

    readback = target.read_text(encoding="utf-8")
    return readback == content, len(payload)


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Генератор предпроектной документации StatNote."
    )
    parser.add_argument("--dir", default="statnote", help="корень репозитория")
    parser.add_argument(
        "--group", default="all",
        choices=["all", "root", "core", "spec", "regs", "context"],
        help="генерировать только указанную группу",
    )
    parser.add_argument("--no-backup", action="store_true", help="без резервных копий")
    parser.add_argument("--dry-run", action="store_true", help="только показать план")
    parser.add_argument("--list", action="store_true", help="перечислить файлы и выйти")
    parser.add_argument(
        "--import-docs", metavar="PATH",
        help="скопировать четыре основных документа из указанной папки в docs/",
    )
    args = parser.parse_args()

    selected = [p for p in FILES if args.group == "all" or GROUP[p] == args.group]

    if args.list:
        print(f"Файлов в генераторе: {len(FILES)}\n")
        for group in ["root", "core", "spec", "regs", "context"]:
            paths = [p for p in FILES if GROUP[p] == group]
            print(f"[{group}]")
            for path in paths:
                print(f"  {path:<42} {PURPOSE[path]}")
            print()
        return

    root = Path(args.dir).expanduser().resolve()
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")

    print(f"Корень: {root}")
    print(f"Группа: {args.group}   файлов: {len(selected)}")
    print(f"Режим: {'план' if args.dry_run else 'запись'}\n")

    if args.dry_run:
        for path in selected:
            mark = "существует" if (root / path).exists() else "новый"
            print(f"  [{mark:>10}] {path}")
        print("\nИзменений не внесено.")
        return

    root.mkdir(parents=True, exist_ok=True)
    total_bytes = 0
    failures = 0
    current_group = None

    for path in selected:
        group = GROUP[path]
        if group != current_group:
            print(f"[{group}]")
            current_group = group

        ok, size = write_file(root / path, FILES[path], not args.no_backup, stamp)
        total_bytes += size
        if not ok:
            failures += 1
        status = "ok" if ok else "MISMATCH"
        print(f"  {path:<42} {size:>7,} байт  [{status}]")

    imported = 0
    if args.import_docs:
        source = Path(args.import_docs).expanduser().resolve()
        print("\n[import]")
        for name in MAIN_DOCS:
            src = source / name
            if not src.exists():
                print(f"  пропущен, не найден: {src}")
                continue
            text = src.read_text(encoding="utf-8")
            ok, size = write_file(root / "docs" / name, text, not args.no_backup, stamp)
            total_bytes += size
            imported += 1
            print(f"  docs/{name:<37} {size:>7,} байт  [{'ok' if ok else 'MISMATCH'}]")

    print(f"\nГотово: {len(selected)} файлов, импортировано {imported}, всего {total_bytes:,} байт.")
    if failures:
        print(f"ВНИМАНИЕ: {failures} файл(ов) не прошли верификацию.")
    else:
        print("Верификация пройдена.")

    print("\nСледующие шаги:")
    print("  1. git init и первый коммит с тегом [M0] docs: preliminary documentation")
    print("  2. Прочитать docs/OPEN_QUESTIONS.md и закрыть блокирующие вопросы")
    print("  3. Начать сессию M0 по контекстному пакету из docs/context_bundles/cb_f0.md")


if __name__ == "__main__":
    main()