def main() -> None:
    parser = argparse.ArgumentParser(
        description="Создание комплекта документации StatNote (4 файла, UTF-8)."
    )
    parser.add_argument(
        "--dir", default="statnote_docs",
        help="целевая папка (по умолчанию: statnote_docs)",
    )
    parser.add_argument(
        "--no-backup", action="store_true",
        help="не создавать резервные копии существующих файлов",
    )
    args = parser.parse_args()

    out_dir = Path(args.dir).expanduser().resolve()
    out_dir.mkdir(parents=True, exist_ok=True)
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")

    print(f"Целевая папка: {out_dir}\n")
    total_bytes = 0
    failures = 0

    for name, raw_text in DOCUMENTS.items():
        target = out_dir / name

        # Резервная копия существующего файла
        if target.exists() and not args.no_backup:
            backup = target.with_name(f"{target.name}.{stamp}.bak")
            shutil.copy2(target, backup)
            print(f"  [backup] {backup.name}")

        # Нормализация: убираем лишние пустые строки, один \n в конце
        content = raw_text.lstrip("\n").rstrip() + "\n"
        data = content.encode("utf-8")
        target.write_bytes(data)

        # Верификация: читаем обратно и сравниваем
        readback = target.read_text(encoding="utf-8")
        ok = readback == content
        size = target.stat().st_size
        total_bytes += size
        if not ok:
            failures += 1

        status = "ok" if ok else "MISMATCH"
        print(f"  [write]  {name}: {len(content):,} символов, {size:,} байт [{status}]")

    print(f"\nГотово: {len(DOCUMENTS)} файла(ов), суммарно {total_bytes:,} байт.")
    if failures:
        print(f"ВНИМАНИЕ: {failures} файл(ов) не прошли верификацию — проверьте вручную.")
    else:
        print("Верификация пройдена: все файлы записаны корректно.")
    print("\nСледующий шаг: перенесите документы в git-репозиторий,")
    print("заполните PROJECT_CONTEXT.md и запишите ADR-01…ADR-16.")


if __name__ == "__main__":
    main()